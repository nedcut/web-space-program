import { chromium } from 'file:///C:/wsp-tools/drv/node_modules/playwright-core/index.mjs';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const out = fileURLToPath(new URL('../docs/screenshots/wp3/verification/', import.meta.url));
mkdirSync(out, { recursive: true });
const browser = await chromium.connectOverCDP('http://127.0.0.1:9333');
const results = [];
try {
 const context = await browser.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 2 });
 await context.addInitScript(() => localStorage.setItem('wsp.settings.v1', JSON.stringify({ quality: 'medium', graphicsProfile: 99, adaptiveQuality: false, autoSaveInterval: 0, masterVolume: 0 })));
 const page = await context.newPage();
 page.on('pageerror', e => { throw e; });
 const waitReady = async () => { await page.waitForFunction(() => window.__flight && !document.querySelector('.loading-screen'), null, { timeout: 120000 }); await page.waitForTimeout(1500); };
 await page.goto('http://172.24.204.38:5401/?flight=stock-meridian'); await waitReady();
 if (await page.locator('.quick-start-row').count() !== 6) throw Error('Missing six-key card');
 if (await page.locator('.modal-backdrop').count()) throw Error('First flight blocks input');
 await page.screenshot({ path: `${out}/first-flight.png` });
 await page.keyboard.press('t'); await page.keyboard.press('z'); await page.keyboard.press('Space');
 await page.waitForTimeout(1700);
 if (await page.locator('.hud-msg').count() > 2) throw Error('Too many liftoff messages');
 if (await page.getByText('Engines not staged', { exact: false }).count()) throw Error('Contradictory engine message');
 await page.screenshot({ path: `${out}/liftoff.png` });
 await page.waitForFunction(() => window.__flight.lastTelemetry?.feel.hint?.id === 'turn', null, { timeout: 45000 });
 const turn = await page.evaluate(() => ({ speed: window.__flight.lastTelemetry.speed, hint: window.__flight.lastTelemetry.feel.hint }));
 if (turn.speed < 50 || turn.speed > 100) throw Error('Late turn hint');
 await page.screenshot({ path: `${out}/gravity-turn.png` }); results.push({ turn });
 await page.keyboard.press('Shift+F1');
 await page.getByRole('dialog', { name: 'Flight controls' }).waitFor();
 if (await page.getByText(/not available yet|Interior view/).count()) throw Error('Unfinished features visible');
 await page.keyboard.press('Escape');
 await page.goto('http://172.24.204.38:5401/?flight=stock-selene&scenario=orbit'); await waitReady();
 if (await page.evaluate(() => window.__flight.speedMode) !== 'orbit') throw Error('Orbit auto mode missing');
 for (const mode of ['surface', 'orbit', 'orbit']) {
   await page.locator('.nb-speed').click(); await page.waitForTimeout(250);
   if (await page.evaluate(() => window.__flight.speedMode) !== mode) throw Error(`Expected ${mode}`);
 }
 if (await page.evaluate(() => window.__flight.speedReference.selection) !== 'auto') throw Error('Cannot return to Auto');
 if ((await page.locator('.engineering-strip').count()) !== 0) throw Error('Engineering strip should default off');
 await page.getByRole('button', { name: /Engineering strip:/ }).click();
 await page.waitForTimeout(300);
 if (!(await page.locator('.engineering-strip').innerText()).includes('Burn in\n—')) throw Error('Circular orbit has a burn countdown');
 await page.screenshot({ path: `${out}/orbit.png` });
 await page.goto('http://172.24.204.38:5401/?flight=stock-selene&scenario=rendezvous'); await waitReady();
 await page.evaluate(() => window.__flight.speedReference.select('auto'));
 await page.waitForTimeout(300);
 if (await page.evaluate(() => window.__flight.speedMode) !== 'target') throw Error('Nearby vessel not Target');
 await page.screenshot({ path: `${out}/target.png` });
 await page.evaluate(() => window.__flight.setTarget(null)); await page.waitForTimeout(300);
 if (await page.evaluate(() => window.__flight.speedMode) !== 'orbit') throw Error('Lost target has wrong fallback');
 await page.goto('http://172.24.204.38:5401/?mission=suicide-burn'); await waitReady();
 await page.evaluate(() => window.__flight.startAssist('land'));
 await page.waitForFunction(() => { const t = window.__flight.lastTelemetry; return t.altitudeTerrain < 250 && t.altitudeTerrain > 40 && t.throttle > 0; }, null, { timeout: 90000 });
 const descent = await page.evaluate(() => { const t = window.__flight.lastTelemetry; return { altitude: t.altitudeTerrain, speed: t.verticalSpeed, throttle: t.throttle, alerts: t.feel.alerts, engineering: t.engineering }; });
 if (descent.alerts.some(a => a.id === 'terrain')) throw Error('Terrain caution during nominal assisted braking');
 if (descent.engineering.stageDeltaV <= 0) throw Error('Pre-ignited engine has zero delta-v');
 await page.screenshot({ path: `${out}/powered-descent.png` });
 results.push({ descent });
 results.push({ firstFlight: 'six keys, non-modal', liftoff: 'at most two messages; no unstaged toast', manualCycle: 'surface/orbit/auto', target: 'auto nearby; orbit on loss', orbitCountdown: 'none' });
 writeFileSync(`${out}/checks.json`, JSON.stringify(results, null, 2));
 await context.close();
 console.log('WP3 browser assertions passed', JSON.stringify(results));
} finally { await browser.close(); }

// Builds src/data/earthCities.ts from Natural Earth 1:10m populated places (public domain).
// Usage: node scripts/earth-cities/build.mjs <path/to/ne_10m_populated_places_simple.dbf>
// Source: https://naciscdn.org/naturalearth/10m/cultural/ne_10m_populated_places_simple.zip (v5.1.2)
import { readFileSync, writeFileSync } from 'node:fs';

const TOP = 400, CAPITAL_MIN_POP = 300_000;
const dbf = readFileSync(process.argv[2]);
const count = dbf.readUInt32LE(4), headerLength = dbf.readUInt16LE(8), recordLength = dbf.readUInt16LE(10);
const fields = [];
for (let at = 32, offset = 1; dbf[at] !== 0x0d; at += 32) {
  const name = dbf.toString('latin1', at, at + 11).replace(/\0.*$/s, '');
  const length = dbf[at + 16];
  fields.push({ name, offset, length });
  offset += length;
}
const field = Object.fromEntries(fields.map(f => [f.name, f]));
const text = (record, name) => dbf.toString('utf8', record + field[name].offset, record + field[name].offset + field[name].length).trim();
const places = [];
for (let i = 0; i < count; i++) {
  const record = headerLength + i * recordLength;
  if (dbf[record] === 0x2a) continue; // deleted
  places.push({
    name: text(record, 'name'), country: text(record, 'adm0name'),
    lat: Number(text(record, 'latitude')), lon: Number(text(record, 'longitude')),
    pop: Number(text(record, 'pop_max')), capital: text(record, 'adm0cap') === '1',
  });
}
places.sort((a, b) => b.pop - a.pop || a.name.localeCompare(b.name));
const chosen = places.filter((p, i) => i < TOP || (p.capital && p.pop >= CAPITAL_MIN_POP));
const rows = chosen.map(p => `  [${JSON.stringify(p.name)}, ${p.lat.toFixed(3)}, ${p.lon.toFixed(3)}, ${p.pop}${p.capital ? ', 1' : ''}],`);
writeFileSync(new URL('../../src/data/earthCities.ts', import.meta.url), `// Generated by scripts/earth-cities/build.mjs from Natural Earth 1:10m populated places v5.1.2 (public domain).
// Do not edit by hand. ${chosen.length} places: the ${TOP} most populous plus national capitals of ${CAPITAL_MIN_POP.toLocaleString('en-US')} or more.

/** Name, latitude (°), longitude (°), population (metro estimate), national capital flag; most populous first. */
export type EarthCity = readonly [name: string, lat: number, lon: number, population: number, capital?: 1];

export const EARTH_CITIES: readonly EarthCity[] = [
${rows.join('\n')}
];
`);
console.log(`${chosen.length} cities written`);

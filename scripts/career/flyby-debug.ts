import '../earth-data/register';
import { World } from '../../src/game/world';
import { Universe } from '../../src/game/universe';
import { PART_CATALOG } from '../../src/data/parts';
import { DEFAULT_START_UT } from '../../src/game/store';
import { buildChallengingOrbiter, buildRealOrbiter } from '../../src/editor/stockCrafts';
import { deorbitAndRecover, freeReturnFlyby, sensor, toOrbit, buy } from './flights';
const preset = (process.argv[2] ?? 'challenging') as 'challenging' | 'real';
const w = new World(new Universe(preset), PART_CATALOG, DEFAULT_START_UT, 'sandbox');
w.mode = 'science' as never;
w.progression.unlocked = ['foundation', 'propulsion-0', 'propulsion-1', 'propulsion-2', 'structures-0', 'structures-1', 'structures-2', 'energy-0', 'discovery-0'];
const b = new Set<string>();
console.log(buy(w, sensor(preset === 'real' ? buildRealOrbiter() : buildChallengingOrbiter())).problem);
let err = toOrbit(w, b, preset === 'real' ? 220000 : 140000, 2) ?? freeReturnFlyby(w, b, 0);
console.log('before entry', err, w.active && w.orbitSummary(w.active).pe, w.active?.state.parts.map(p => `${p.def.id}@${p.stage}`).join(' '));
w.onEvent = (e: any) => { if (['partDestroyed', 'chute', 'structuralFailure', 'decouple', 'vesselDestroyed'].includes(e.type)) console.log((w.ut - DEFAULT_START_UT).toFixed(0), JSON.stringify(e).slice(0, 200)); };
let maxG = 0; const t0 = w.tick.bind(w); (w as any).tick = (dt: number, i: any) => { t0(dt, i); if (w.active) maxG = Math.max(maxG, w.active.state.telemetry.gForce); };
err = err ?? deorbitAndRecover(w, b);
console.log('result', err, 'maxG', maxG.toFixed(1));

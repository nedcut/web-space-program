import * as THREE from 'three';
import { createUniverse } from '../sim/bodies';
import { createEphemeris } from '../sim/orbit/ephemeris';
import { MapView } from '../render/map/MapView';
import { DEFAULT_START_UT } from '../game/store';

const params = new URLSearchParams(location.search);
const bodies = createUniverse((params.get('scale') as 'standard') ?? 'standard');
const ephem = createEphemeris(bodies);
const renderer = new THREE.WebGLRenderer({ antialias: true, logarithmicDepthBuffer: true });
renderer.setPixelRatio(devicePixelRatio);
renderer.setSize(innerWidth, innerHeight);
document.body.appendChild(renderer.domElement);
const map = new MapView(bodies, ephem, document.body);
let focusId = params.get('focus') ?? 'sun';
map.distance = +(params.get('dist') ?? 6e11);
map.attachControls(renderer.domElement, () => (bodies.get(focusId)!.radius * 1.5));
const ui = document.getElementById('ui')!;
const sel = document.createElement('select');
for (const b of bodies.values()) sel.add(new Option(b.name, b.id, false, b.id === focusId));
sel.onchange = () => { focusId = sel.value; map.distance = Math.max(bodies.get(focusId)!.radius * 6, 1e6); };
ui.appendChild(sel);
let t = DEFAULT_START_UT;
const loop = () => {
  t += +(params.get('rate') ?? 0);
  map.update({ t, focusId, focus: ephem.getBodyState(focusId, t).position, viewport: { width: innerWidth, height: innerHeight } });
  renderer.render(map.scene, map.camera);
  requestAnimationFrame(loop);
};
loop();

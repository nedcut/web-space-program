/** Real SI source data, never gameplay-scaled.
 * Sources:
 * https://ssd.jpl.nasa.gov/planets/approx_pos.html (J2000, 1800–2050 fit)
 * https://ssd.jpl.nasa.gov/sats/elem/ (mean satellite elements, not precision ephemerides)
 * https://ssd.jpl.nasa.gov/sats/phys_par/ and /planets/phys_par.html (GM and mean radii)
 * https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/gm_de440.tpc
 * https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/pck00011.tpc (IAU WGCCRE pole constants)
 * https://nssdc.gsfc.nasa.gov/planetary/planetfact.html (rotation, obliquity, atmospheres)
 * Ceres: JPL Horizons heliocentric ecliptic elements at JD 2451545.0, solution JPL#48.
 * Pole values use the IAU constant terms; nutation/precession are outside this on-rails model.
 * Laplace planes are represented as parentEquator by the simulation contract; outer moon
 * planes (especially Iapetus/Phoebe) therefore have an approximate inertial orientation.
 * Earth uses JPL's Earth–Moon barycenter heliocentric fit, Pluto its system barycenter fit.
 * Nereid's 2020 mean elements are carried back to J2000 with their mean secular rates.
 * Unmeasured spin obliquities use zero (idealized synchronous rotation for regular moons);
 * Hyperion has no fixed pole. Small moon masses without measured GM use noted estimates.
 * Colours, relief, seeds and scattering hints are procedural art parameters, not measurements.
 */
const DEG = Math.PI / 180;
const AU = 149597870700;
const DAY = 86400;

function orbit(a: number, e: number, i: number, lan: number, argPe: number, meanAnomaly: number,
  frame: OrbitalElements['frame'] = 'ecliptic'): OrbitalElements {
  return { a, e, i: i * DEG, lan: lan * DEG, argPe: argPe * DEG,
    meanAnomalyAtEpoch: meanAnomaly * DEG, epoch: 0, frame };
}


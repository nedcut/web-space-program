function surface(id: string, preset: string, relief: number, colors = PALETTES[preset]): SurfaceStyle {
  // Stable per-body FNV-1a seeds; separate palette arrays avoid shared mutable styles.
  let seed = 2166136261;
  for (const c of id) seed = Math.imul(seed ^ c.charCodeAt(0), 16777619) >>> 0;
  return { preset, relief, seed, colors: colors.map(c => [...c] as [number, number, number]),
    ...(id === 'earth' ? { ocean: true } : {}) };
}


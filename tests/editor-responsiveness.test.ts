import { afterEach, expect, it, vi } from 'vitest';
import { EditorSession } from '../src/editor/session';
import { STOCK_CRAFTS } from '../src/editor/stockCrafts';
import { game } from '../src/game/store';
import { v3 } from '../src/util/vec3';
const preset = game.get().scalePreset;
afterEach(() => { game.set({ scalePreset: preset }); vi.useRealTimers(); });
it('reuses derived craft data for held-only core edits, but invalidates resources, staging, undo and scale', () => {
  vi.useFakeTimers();
  const session = new EditorSession(STOCK_CRAFTS.find(s => s.id === 'stock-selene')!.build());
  const uid = session.getSnapshot().craft.parts.find(p => p.parent !== undefined)!.uid;
  session.pickUp(uid);
  const detached = session.getSnapshot();
  session.editor.rotateHeld({ x: 0, y: 0, z: 1, w: 0 });
  expect(session.getSnapshot().craft).toBe(detached.craft);
  expect(session.getSnapshot().stats).toBe(detached.stats);
  expect(session.getSnapshot().stageStats).toBe(detached.stageStats);
  session.cancelHeld();
  const restored = session.getSnapshot();
  expect(restored.craft.parts.length).toBeGreaterThan(detached.craft.parts.length);
  expect(restored.stats).not.toBe(detached.stats);
  const tank = restored.craft.parts.find(p => p.partId.startsWith('tank'))!;
  session.setPartResources(tank.uid, { liquidFuel: 0, oxidizer: 0 });
  expect(session.getSnapshot().stats.totalMass).toBeLessThan(restored.stats.totalMass);
  expect(session.getSnapshot().stageStats).not.toBe(restored.stageStats);
  session.undo();
  expect(session.getSnapshot().stats.totalMass).toBe(restored.stats.totalMass);
  const beforeStage = session.getSnapshot();
  session.insertStage(0);
  expect(session.getSnapshot().stages).not.toBe(beforeStage.stages);
  const beforeScale = session.getSnapshot().stageStats;
  game.set({ scalePreset: 'real' });
  session.removeEmptyStages(); // Emits unchanged craft, but reference conditions changed.
  expect(session.getSnapshot().stageStats).not.toBe(beforeScale);
  session.pickNew('tank-1-short');
  const beforeUi = session.getSnapshot();
  session.rotateHeld(v3(0, 1, 0), 0.1);
  expect(session.getSnapshot().stageStats).toBe(beforeUi.stageStats);
});
